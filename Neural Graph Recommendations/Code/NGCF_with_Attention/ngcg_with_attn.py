    def _aggx(self, center_ids, ego_embeddings, k,is_user=True):
      device = ego_embeddings.device
      batch_size = center_ids.shape[0]
      dim = ego_embeddings.shape[1]
      attn_k = self.user_neighbors.shape[1]  # assumes padded
      center_ids = center_ids.clamp(max=self.n_item - 1)# new addiion
      center_ids = center_ids.to(device)  # 🛠️ Ensure center_ids is on correct device

      if is_user:
          neighbor_ids = self.user_neighbors[center_ids]            # (B, K)
          center_embeddings = ego_embeddings[center_ids]               # (B, D)
          neighbor_embeddings = ego_embeddings[self.n_user + neighbor_ids]  # (B, K, D)
      else:
          neighbor_ids = self.item_neighbors[center_ids]           # (B, K)
          center_embeddings = ego_embeddings[self.n_user + center_ids] # (B, D)
          neighbor_embeddings = ego_embeddings[neighbor_ids]           # (B, K, D)

      center_expanded = center_embeddings.unsqueeze(1).repeat(1, attn_k, 1)  # (B, K, D)
      concat = torch.cat([center_expanded, neighbor_embeddings], dim=2)     # (B, K, 2D)
      #print('here-atten',k,is_user,concat.shape,self.weight_dict[f'W_att_{k}'].shape)
      flat = concat.view(batch_size * attn_k, -1)                            # (B*K, 2D)
      scores = torch.tanh(flat @ self.weight_dict[f'W_att_{k}'])                 # (B*K, D)
      scores = scores @ self.weight_dict[f'V_att_{k}']                           # (B*K, 1)
      scores = scores.view(batch_size, 1, attn_k)                           # (B, 1, K)
      weights = torch.softmax(scores, dim=2)                                # (B, 1, K)

      agg_neighbors = torch.bmm(weights, neighbor_embeddings).squeeze(1)    # (B, D)
      return agg_neighbors
      



