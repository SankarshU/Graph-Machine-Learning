def train(args, model):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model = model.to(device)

    optimizer = optim.Adam(model.parameters(), lr=args.lr)

    total_losses, mf_losses, emb_losses = [], [], []

    if args.use_attributes:
        if args.retain_attributes:
            model_type = 'u_embedding_initialization_user_feature/attributes_used_and_frozen'
        else:
            model_type = 'u_embedding_initialization_user_feature/attributes_used_but_updated'
    else:
        model_type = 'u_embedding_initialization_user_feature/attributes_are_notused_randomly_initialized'

    results = []
    #for epoch in range(args.epoch):
    for epoch in tqdm(range(args.epoch), desc="📅 Training Epochs"):

        epoch_loss, epoch_mf_loss, epoch_emb_loss = 0., 0., 0.
        n_batch = data_generator.n_train // args.batch_size + 1

        for idx in range(n_batch):
            users, pos_items, neg_items = data_generator.sample()
            users = torch.tensor(users).to(device)
            pos_items = torch.tensor(pos_items).to(device)
            neg_items = torch.tensor(neg_items).to(device)

            u_g_embeddings, pos_i_g_embeddings, neg_i_g_embeddings = model(
                users, pos_items, neg_items, drop_flag=args.node_dropout_flag)

            batch_loss, batch_mf_loss, batch_emb_loss = model.create_bpr_loss(
                u_g_embeddings, pos_i_g_embeddings, neg_i_g_embeddings)

            optimizer.zero_grad()
            batch_loss.backward()
            optimizer.step()

            epoch_loss += batch_loss.item()
            epoch_mf_loss += batch_mf_loss.item()
            epoch_emb_loss += batch_emb_loss.item()

        total_losses.append(epoch_loss)
        mf_losses.append(epoch_mf_loss)
        emb_losses.append(epoch_emb_loss)

        print(f"Epoch {epoch} completed: Total Loss={epoch_loss:.4f}, MF Loss={epoch_mf_loss:.4f}, Emb Loss={epoch_emb_loss:.4f}")
        results.append((model_type, epoch, round(epoch_loss, 4)))

    # Plot losses
    epochs = range(args.epoch)
    plt.figure(figsize=(10,6))
    #plt.plot(epochs, total_losses, label='Total Loss')
    plt.plot(epochs, mf_losses, label='Loss')
    #plt.plot(epochs, emb_losses, label='Embedding Loss')
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.title('Training Losses over Epochs')
    plt.legend()
    plt.grid()
    plt.show()

    return results

