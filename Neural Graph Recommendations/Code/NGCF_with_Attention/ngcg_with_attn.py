    def init_weight(self):
      # === Weight Initialization ===
      initializer = nn.init.xavier_uniform_

      # === Embedding Initialization ===
      embedding_dict = nn.ParameterDict({
          'user_emb': nn.Parameter(initializer(torch.empty(self.n_user, self.emb_size))),
          'item_emb': nn.Parameter(initializer(torch.empty(self.n_item, self.emb_size)))
      })

      # === Optional: Use attribute-based embeddings ===
      if self.use_attributes:
          print('*** user/item embeddings are initialized with features/attributes ***')
          tar = np.load(save_path + 'user_features.npy')
          war = np.load(save_path + 'item_features.npy')
          embedding_dict['user_emb'].data = torch.FloatTensor(tar)
          embedding_dict['item_emb'].data = torch.FloatTensor(war)

          if self.retain_attributes:
              print('*** embeddings frozen ***')
              embedding_dict['user_emb'].requires_grad = False
              embedding_dict['item_emb'].requires_grad = False
          else:
              print('*** embeddings trainable ***')

      # === Message Passing Weights ===
      weight_dict = nn.ParameterDict()
      layers = [self.emb_size] + self.layers
      for k in range(len(self.layers)):
          weight_dict.update({
              f'W_gc_{k}': nn.Parameter(initializer(torch.empty(layers[k], layers[k+1]))),
              f'b_gc_{k}': nn.Parameter(initializer(torch.empty(1, layers[k+1]))),
              f'W_bi_{k}': nn.Parameter(initializer(torch.empty(layers[k], layers[k+1]))),
              f'b_bi_{k}': nn.Parameter(initializer(torch.empty(1, layers[k+1]))),
          })
          att_in_dim = 2 * layers[k]         # [center || neighbor]
          att_hidden_dim = layers[k+1]       # project to match next layer

          weight_dict[f'W_att_{k}'] = nn.Parameter(initializer(torch.empty(att_in_dim, att_hidden_dim)))
          weight_dict[f'V_att_{k}'] = nn.Parameter(initializer(torch.empty(att_hidden_dim, 1)))

          print(f"DEBUG W_att_{k} shape: {att_in_dim} → {att_hidden_dim}")
      return embedding_dict, weight_dict


    def _convert_sp_mat_to_sp_tensor(self, X):
        coo = X.tocoo()
        i = torch.LongTensor([coo.row, coo.col])
        v = torch.from_numpy(coo.data).float()
        return torch.sparse.FloatTensor(i, v, coo.shape)

    def sparse_dropout(self, x, rate, noise_shape):
        random_tensor = 1 - rate
        random_tensor += torch.rand(noise_shape).to(x.device)
        dropout_mask = torch.floor(random_tensor).type(torch.bool)
        i = x._indices()
        v = x._values()

        i = i[:, dropout_mask]
        v = v[dropout_mask]

        out = torch.sparse.FloatTensor(i, v, x.shape).to(x.device)
        return out * (1. / (1 - rate))

    def create_bpr_loss(self, users, pos_items, neg_items):
        pos_scores = torch.sum(torch.mul(users, pos_items), axis=1)
        neg_scores = torch.sum(torch.mul(users, neg_items), axis=1)

        maxi = nn.LogSigmoid()(pos_scores - neg_scores)

        mf_loss = -1 * torch.mean(maxi)

        # cul regularizer
        regularizer = (torch.norm(users) ** 2
                       + torch.norm(pos_items) ** 2
                       + torch.norm(neg_items) ** 2) / 2
        emb_loss = self.decay * regularizer / self.batch_size

        return mf_loss + emb_loss, mf_loss, emb_loss

