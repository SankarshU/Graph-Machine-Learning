    def _build_neighbors(self, mapping_dict, total_count, attn_k):
        neighbors = []
        for idx in range(total_count):
            ids = mapping_dict.get(idx, [])
            if len(ids) == 0:
                padded = [0] * attn_k
            elif len(ids) < attn_k:
                padded = ids + [ids[-1]] * (attn_k - len(ids))
            else:
                padded = ids[:attn_k]
            neighbors.append(padded)
        return torch.tensor(neighbors, dtype=torch.long)
