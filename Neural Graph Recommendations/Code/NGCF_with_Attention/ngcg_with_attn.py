    def forward(self, users, pos_items, neg_items, drop_flag=True):
    # === Step 1: Sparse dropout ===
        A_hat = self.sparse_dropout(self.sparse_norm_adj,
                                    self.node_dropout,
                                    self.sparse_norm_adj._nnz()) if drop_flag else self.sparse_norm_adj
        self.model_A_hat = A_hat
    
        # === Step 2: Initial Embedding Setup ===
        ego_embeddings = torch.cat([
            self.embedding_dict['user_emb'],
            self.embedding_dict['item_emb']
        ], dim=0).type(torch.float32)  # Ensure float32
    
        expected_nodes = self.n_user + self.n_item
        if ego_embeddings.shape[0] != expected_nodes:
            print(f"⚠️ Trimming initial ego_embeddings: {ego_embeddings.shape[0]} → {expected_nodes}")
            ego_embeddings = ego_embeddings[:expected_nodes]
    
        all_embeddings = [ego_embeddings]
    
        # === Step 3: Layer-wise Propagation ===
        for k in range(len(self.layers)):
            user_ids = torch.arange(self.n_user, device=ego_embeddings.device)
            item_ids = torch.arange(self.n_item, device=ego_embeddings.device)
    
            # --- Optional Attention Aggregation ---
            if self.use_attn:
                user_agg = self._agg(user_ids, ego_embeddings, k, is_user=True)
                item_agg = self._agg(item_ids, ego_embeddings, k, is_user=False)
                ego_embeddings = torch.cat([user_agg, item_agg], dim=0)
    
            # ✅ Trim ego_embeddings for safety (works even without attention)
            if ego_embeddings.shape[0] != expected_nodes:
                print(f"⚠️ Trimming ego_embeddings at layer {k}: {ego_embeddings.shape[0]} → {expected_nodes}")
                ego_embeddings = ego_embeddings[:expected_nodes]
    
            # --- Message Passing ---
            side_embeddings = torch.sparse.mm(A_hat, ego_embeddings)
    
            # Transformed sum message
            sum_embeddings = torch.matmul(side_embeddings, self.weight_dict[f'W_gc_{k}']) \
                             + self.weight_dict[f'b_gc_{k}']
    
            # Transformed bi interaction
            bi_embeddings = torch.mul(ego_embeddings, side_embeddings)
            bi_embeddings = torch.matmul(bi_embeddings, self.weight_dict[f'W_bi_{k}']) \
                            + self.weight_dict[f'b_bi_{k}']
    
            # LeakyReLU + Dropout + Normalize
            ego_embeddings = F.leaky_relu(sum_embeddings + bi_embeddings, negative_slope=0.2)
            ego_embeddings = F.dropout(ego_embeddings, p=self.mess_dropout[k], training=self.training)
            norm_embeddings = F.normalize(ego_embeddings, p=2, dim=1)
    
            all_embeddings.append(norm_embeddings)
    
        # === Step 4: Final Concatenation ===
        all_embeddings = torch.cat(all_embeddings, dim=1)
        u_g_embeddings = all_embeddings[:self.n_user, :]
        i_g_embeddings = all_embeddings[self.n_user:, :]
    
        # === Step 5: Gather Output Embeddings for BPR Loss ===
        u_g_embeddings = u_g_embeddings[users, :]
        pos_i_g_embeddings = i_g_embeddings[pos_items, :]
        neg_i_g_embeddings = i_g_embeddings[neg_items, :]
    
        return u_g_embeddings, pos_i_g_embeddings, neg_i_g_embeddings

